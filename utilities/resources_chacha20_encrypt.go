func (d *chacha20EncryptResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var plan, state chacha20EncryptResourceModel

	diags := req.Config.Get(ctx, &plan)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}

	state = plan

	aad := plan.AdditionalAuthenticatedData.ValueString()
	encrypted, err := encryptChaCha20(plan.SecretKey.ValueString(), plan.Nonce.ValueString(), plan.StringValue.ValueString(), aad)
	if err != nil {
		resp.Diagnostics.AddError("[Error] Failed to encrypt value", err.Error())
		return
	}
	state.EncryptedStringOutput = types.StringValue(encrypted)

	diags = resp.State.Set(ctx, &state)
	resp.Diagnostics.Append(diags...)
	if resp.Diagnostics.HasError() {
		return
	}
}

