// chacha20EncryptOutput is the JSON structure returned by encryptChaCha20.
type chacha20EncryptOutput struct {
	Nonce      string `json:"nonce"`
	Ciphertext string `json:"ciphertext"`
	Tag        string `json:"tag"`
}

// encryptChaCha20 prepares the input and encrypts it with XChaCha20-Poly1305
// AEAD. The input may be either a JSON string or a plain string: if it parses
// as valid JSON it is minified (compacted) and trimmed; otherwise it is treated
// as a plain string and merely trimmed. The 32-byte key is derived from the
// provided key (a 64-character hex string representing 32 bytes). The nonce
// is supplied by the caller as a hex-encoded string (e.g. the .hex output of
// the random_bytes ephemeral resource); it is hex-decoded to its raw bytes,
// and those raw bytes -- not the encoded string -- are used directly as the
// XChaCha20 nonce (exactly 24 bytes after decoding, the extended 192-bit
// XChaCha20 nonce) and must be unique for every encryption under the same
// key. The optional AAD (additional authenticated data) is authenticated but
// not encrypted. The Poly1305 auth tag provides integrity. It returns a JSON
// string with three separate fields:
//
//	{"nonce":"<hex>","ciphertext":"<base64>","tag":"<raw>"}
//
// where ciphertext includes the 16-byte Poly1305 auth tag (needed for
// decryption), and tag is the raw (unencoded) additional authenticated data.
func encryptChaCha20(key, nonce, input, aad string) (string, error) {
	// Determine the plaintext to encrypt. If the input is valid JSON, minify
	// (compact) and trim it; otherwise treat it as a plain string and just
	// trim it.
	plaintext := strings.TrimSpace(input)

	var jsonValue interface{}
	if err := json.Unmarshal([]byte(input), &jsonValue); err == nil {
		minifiedBytes, err := json.Marshal(jsonValue)
		if err != nil {
			return "", fmt.Errorf("failed to minify JSON: %w", err)
		}
		plaintext = strings.TrimSpace(string(minifiedBytes))
	}

	// Decode the hex-encoded 32-byte key.
	keyBytes, err := hex.DecodeString(key)
	if err != nil {
		return "", fmt.Errorf("invalid hex key: %w", err)
	}

	aead, err := chacha20poly1305.NewX(keyBytes)
	if err != nil {
		return "", fmt.Errorf("failed to create xchacha20-poly1305 aead: %w", err)
	}

	// The nonce is hex-decoded to its raw bytes, and those raw bytes are
	// used directly as the XChaCha20 nonce. It must decode to exactly
	// chacha20poly1305.NonceSizeX (24) bytes -- the extended 192-bit
	// XChaCha20 nonce. This means the .hex output of the random_bytes
	// ephemeral resource (length = 24) yields the 24 generated bytes as the
	// nonce, not the 48-character hex string itself. The nonce is
	// caller-supplied so the output is deterministic for a given
	// (key, nonce, plaintext, AAD) tuple; it must be unique per key.
	nonceBytes, err := hex.DecodeString(nonce)
	if err != nil {
		return "", fmt.Errorf("invalid hex nonce: %w", err)
	}

	if len(nonceBytes) != chacha20poly1305.NonceSizeX {
		return "", fmt.Errorf("nonce must be exactly %d bytes (48 hexadecimal characters) after hex-decoding, got %d bytes", chacha20poly1305.NonceSizeX, len(nonceBytes))
	}

	// Seal encrypts the plaintext and appends a 16-byte Poly1305 auth tag.
	// AAD (if provided) is authenticated but not encrypted. The auth tag is
	// part of the ciphertext (needed for decryption).
	sealed := aead.Seal(nil, nonceBytes, []byte(plaintext), []byte(aad))

	output := chacha20EncryptOutput{
		Nonce:      nonce,
		Ciphertext: base64.StdEncoding.EncodeToString(sealed),
		Tag:        aad,
	}

	outputJSON, err := json.Marshal(output)
	if err != nil {
		return "", fmt.Errorf("failed to marshal output json: %w", err)
	}

	return string(outputJSON), nil
}
