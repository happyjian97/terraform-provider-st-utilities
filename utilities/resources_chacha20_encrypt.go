func NewChacha20EncryptResource() resource.Resource {
	return &chacha20EncryptResource{}
}

type chacha20EncryptResource struct{}

type chacha20EncryptResourceModel struct {
	SecretKey                   types.String `tfsdk:"secret_key"`
	Nonce                       types.String `tfsdk:"nonce"`
	StringValue                 types.String `tfsdk:"string_value"`
	AdditionalAuthenticatedData types.String `tfsdk:"additional_authenticated_data"`
	Version                     types.Int64  `tfsdk:"version"`
	EncryptedStringOutput       types.String `tfsdk:"encrypted_string_output"`
}

func (d *chacha20EncryptResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_chacha20_encrypt"
}

